#!/usr/bin/env python3
"""Generate the Switch build's bank registry from a generated bank directory.

The desktop runner has CMake generate this registry, but the AArch64 build in
`switch-port/` is a hand-written compile script, so its registry has to be
produced the same way: one `nds_register_dispatch` call per bank, gated behind
the exact cartridge SHA-1 that the banks were generated from, with the CPU
inferred from the `_arm9_`/`_arm7_` name segment.

PRIVATE TOOLING: the registry it writes names ROM-derived symbols. The file is
only ever linked into the private NRO, never published.

Usage:
    python tools/gen_switch_registry.py <bank-dir> [--out <path>]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROM_SHA1 = "5f35bfbf79a0947740795dd770d99e8eea3ac85e"
HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE.parent / "switch-port" / "src" / "title_bank_registry.cpp"


def bank_cpu(name: str) -> tuple[str, str]:
    parts = name.split("_")
    if "arm9" in parts:
        return "NDS_ARM9", "0xFFFF0000u"
    if "arm7" in parts:
        return "NDS_ARM7", "0x00000000u"
    raise SystemExit(f"cannot infer CPU from bank name: {name}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("banks", type=Path)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--rom-sha1", default=ROM_SHA1)
    args = ap.parse_args()

    dispatch = sorted(args.banks.glob("*_dispatch.c"))
    if not dispatch:
        raise SystemExit(f"no *_dispatch.c in {args.banks}")
    banks = [p.name[: -len("_dispatch.c")] for p in dispatch]

    lines = [
        "// title_bank_registry.cpp -- generated-bank registration for the "
        "Switch build.",
        "//",
        "// GENERATED by tools/gen_switch_registry.py from a bank directory. "
        "PRIVATE BUILD",
        "// ONLY: these banks are recompiled from the user's own cartridge and "
        "are never",
        "// part of a published release. The public build omits this "
        "translation unit and",
        "// the bank objects entirely, falling back to the Tier-3 interpreter.",
        "",
        "#include <cstring>",
        "",
        '#include "state.h"',
        '#include "title_banks.h"',
        "",
    ]
    for bank in banks:
        lines += [f"extern \"C\" const DispatchEntry g_dispatch_{bank}[];",
                  f"extern \"C\" const unsigned g_dispatch_{bank}_len;"]
    lines += ["",
              "bool nds_register_configured_title_banks(const char* rom_sha1) {",
              "    if (!rom_sha1) return false;",
              f'    if (std::strcmp(rom_sha1, "{args.rom_sha1}") != 0)',
              "        return false;"]
    for bank in banks:
        cpu, mask = bank_cpu(bank)
        lines += [f"    nds_register_dispatch({cpu}, g_dispatch_{bank},",
                  f"                          g_dispatch_{bank}_len, {mask});"]
    lines += ["    return true;", "}", ""]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {args.out} with {len(banks)} banks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
